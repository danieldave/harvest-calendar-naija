#!/usr/bin/env node
/* ==========================================================================
   tools/build.js  -  makes the pages Google and AI assistants can read
   --------------------------------------------------------------------------
   From js/data.js (84 crops, 36 states + FCT) it writes:

     /crops/                 all crop guides, grouped by type
     /crops/<crop>/          "When to plant maize in Nigeria"      (84 pages)
     /states/                all states, grouped by region
     /states/<state>/        "What to plant in Ogun State"         (37 pages)
     /sitemap.xml            every page, for Google and Bing        (SEO)
     /robots.txt             welcomes search AND AI search bots     (GEO)
     /llms.txt               a short fact sheet for AI assistants   (GEO)
   and fixes the address (canonical link) at the top of the main pages.

   Every guide page starts with a "Quick answer" and carries FAQ, Article
   and Breadcrumb labels (JSON-LD), so answer engines can quote it  (AEO).

   Run it every time js/data.js changes:      node tools/build.js
   The website address lives in tools/site.json.
   ========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SITE = JSON.parse(fs.readFileSync(path.join(__dirname, 'site.json'), 'utf8'));
const URL_ = SITE.url.replace(/\/$/, '');
const TODAY = new Date().toISOString().slice(0, 10);
const { MONTHS, ZONES, STATES, CATEGORIES, CROPS, SEASONS } = require('../js/data.js');
CROPS.forEach(c => { if (!c.id) c.id = c.n.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''); });

const esc = s => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const json = o => JSON.stringify(o).replace(/</g, '\\u003c');
const write = (rel, text) => { const f = path.join(ROOT, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, text); };
const list = a => a.length <= 1 ? a.join('') : a.slice(0, -1).join(', ') + ' and ' + a[a.length - 1];
const SHORT = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

// "3,4,5,6,8" -> "March to June and August" (handles Nov -> Feb wrap-around)
function monthRange(ms) {
  const set = new Set(ms);
  if (set.size === 12) return 'all year round';
  if (!set.size) return '-';
  let gap = 1; while (set.has(gap)) gap++;                      // start just after a month with no work
  const runs = []; let start = null;
  for (let k = 1; k <= 12; k++) {
    const m = ((gap - 1 + k) % 12) + 1, next = (m % 12) + 1;
    if (set.has(m) && start === null) start = m;
    if (start !== null && !set.has(next)) { runs.push(start === m ? MONTHS[m - 1] : MONTHS[start - 1] + ' to ' + MONTHS[m - 1]); start = null; }
  }
  return list(runs);
}
const zoneNames = zs => zs.map(z => ZONES[z].name);
const cropLocal = c => (c.l || '').split(',').map(s => s.trim()).filter(Boolean);
const localShort = c => cropLocal(c).map(s => s.replace(/\s*\(.*\)/, '')).slice(0, 3);

/* ---------- the shared page frame (header + footer taken from planting.html) ---------- */
const TEMPLATE = fs.readFileSync(path.join(ROOT, 'planting.html'), 'utf8');
const HEADER = TEMPLATE.slice(TEMPLATE.indexOf('<body'), TEMPLATE.indexOf('<main id="main">'))
  .replace(/<body[^>]*>/, '<body data-page="guide">')
  .replace(/ class="active" aria-current="page"/g, '');
const FOOTER = TEMPLATE.slice(TEMPLATE.indexOf('</main>'))
  .replace('<script src="/js/planting.js" defer></script>\n', '');
const THEME_SCRIPT = TEMPLATE.slice(TEMPLATE.indexOf('  <script>'), TEMPLATE.indexOf('</script>') + 9);
const FONTS = '<link rel="preconnect" href="https://fonts.googleapis.com">\n  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n  <link href="https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,400..700&family=Inter:wght@400;500;600;700&display=swap" rel="stylesheet">';
const FAVICON = (TEMPLATE.match(/<link rel="icon"[^>]+>/) || [''])[0];

const PUBLISHER = {
  '@type': 'EducationalOrganization', '@id': URL_ + '/#org', name: SITE.publisher, url: URL_ + '/',
  address: { '@type': 'PostalAddress', addressLocality: 'Ilaro', addressRegion: 'Ogun State', addressCountry: 'NG' },
  parentOrganization: { '@type': 'Organization', name: SITE.parent }
};

function page({ rel, title, description, crumbs, h1, sub, answer, body, schema, keywords }) {
  const url = URL_ + '/' + rel.replace(/index\.html$/, '');
  const graph = [PUBLISHER, { '@type': 'BreadcrumbList', itemListElement: crumbs.map((c, i) => ({ '@type': 'ListItem', position: i + 1, name: c[0], item: URL_ + c[1] })) }].concat(schema || []);
  return `<!DOCTYPE html>
<!-- MADE BY tools/build.js FROM js/data.js. Do not edit this file by hand: change the data, then run  node tools/build.js -->
<html lang="en-NG">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
${THEME_SCRIPT}
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}">
  ${keywords ? `<meta name="keywords" content="${esc(keywords)}">` : ''}
  <meta name="robots" content="index, follow, max-snippet:-1, max-image-preview:large">
  <meta name="theme-color" content="#0f3b25">
  <link rel="canonical" href="${url}">
  <meta property="og:type" content="article">
  <meta property="og:site_name" content="Harvest Calendar Naija">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(description)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${URL_}/images/og-image.png">
  <meta property="og:locale" content="en_NG">
  <meta name="twitter:card" content="summary_large_image">
  ${FAVICON}
  ${FONTS}
  <link rel="stylesheet" href="/style.css">
  <script type="application/ld+json">${json({ '@context': 'https://schema.org', '@graph': graph })}</script>
</head>
${HEADER}<main id="main">
    <section class="page-banner guide-hero">
      <div class="container">
        <nav class="breadcrumb" aria-label="Breadcrumb">${crumbs.map((c, i) => i < crumbs.length - 1 ? `<a href="${c[1]}">${esc(c[0])}</a> <span aria-hidden="true">›</span> ` : `<span aria-current="page">${esc(c[0])}</span>`).join('')}</nav>
        <h1>${h1}</h1>
        ${sub ? `<p class="section-sub">${sub}</p>` : ''}
        ${answer ? `<p class="answer-box"><b>Quick answer:</b> ${answer}</p>` : ''}
      </div>
    </section>
    <section class="section">
      <div class="container">
${body}
        <p class="updated">Written by students of the ${esc(SITE.publisher)} from facts checked against IITA, NAERLS, NRCRI, NIHORT and FAO. Last updated <time datetime="${TODAY}">${TODAY}</time>. A guide, not a promise: always confirm dates with your ADP extension officer.</p>
      </div>
    </section>
  ${FOOTER}`;
}

function monthStrip(c) {
  return `<div class="month-strip" aria-label="Planting and harvest months">${SHORT.map((m, i) => {
    const p = c.p.includes(i + 1), h = c.h.includes(i + 1);
    const cls = p && h ? 'b' : p ? 'p' : h ? 'h' : '';
    const word = p && h ? 'plant and harvest' : p ? 'plant' : h ? 'harvest' : 'no field work';
    return `<span class="${cls}" title="${MONTHS[i]}: ${word}">${m}</span>`;
  }).join('')}</div><p class="note"><span style="color:var(--green-500)">■</span> plant &nbsp; <span style="color:var(--gold-500)">■</span> harvest</p>`;
}
const faqHTML = faq => faq.map(([q, a]) => `<div class="faq-item"><h3>${esc(q)}</h3><p>${esc(a)}</p></div>`).join('');
const faqLD = faq => ({ '@type': 'FAQPage', mainEntity: faq.map(([q, a]) => ({ '@type': 'Question', name: q, acceptedAnswer: { '@type': 'Answer', text: a } })) });
const pages = [];
const stateLink = n => { const s = STATES.find(x => x.n === n); return s ? `<a href="/states/${s.id}/">${esc(n)}</a>` : esc(n); };

/* ---------- /crops/<crop>/ ---------- */
CROPS.forEach(c => {
  const plant = monthRange(c.p), harvest = monthRange(c.h);
  const locals = localShort(c);
  const zones = zoneNames(c.z);
  const allZones = c.z.length >= 6;
  const answer = `Plant <b>${esc(c.n.toLowerCase())}</b> in Nigeria from <b>${esc(plant)}</b> and harvest from <b>${esc(harvest)}</b>. ${esc(c.s || '')}`;
  const plainAnswer = `Plant ${c.n.toLowerCase()} in Nigeria from ${plant} and harvest from ${harvest}. ${c.s || ''}`.trim();
  const faq = [
    [`When is the best time to plant ${c.n.toLowerCase()} in Nigeria?`, plainAnswer],
    [`When is ${c.n.toLowerCase()} harvested in Nigeria?`, `${c.n} is usually harvested from ${harvest}.`],
    [`Which Nigerian states grow the most ${c.n.toLowerCase()}?`, c.st.length ? `${list(c.st)} are among the best-known ${c.n.toLowerCase()} states.` : `${c.n} is grown in small amounts across many states.`],
    [`Can I grow ${c.n.toLowerCase()} in my part of Nigeria?`, allZones ? `Yes. ${c.n} grows in every region of Nigeria: North and South.` : `${c.n} grows best in the ${list(zones)} region${zones.length > 1 ? 's' : ''}. In other regions, ask your ADP extension officer before planting.`],
    [`What diseases attack ${c.n.toLowerCase()} and how do I prevent them?`, c.d.map(d => `${d[0]}: ${d[1]}`).join(' ')]
  ];
  if (locals.length) faq.splice(1, 0, [`What is ${c.n.toLowerCase()} called in Yoruba, Hausa and Igbo?`, `${c.n} is called ${list(cropLocal(c))}.`]);
  const related = CROPS.filter(x => x.c === c.c && x.id !== c.id).slice(0, 8);
  const body = `
        <div class="facts">
          <div class="fact"><small>Plant</small><b>${esc(plant)}</b></div>
          <div class="fact"><small>Harvest</small><b>${esc(harvest)}</b></div>
          <div class="fact"><small>Grows in</small><b>${esc(allZones ? 'All regions' : list(zones))}</b></div>
          <div class="fact"><small>Type</small><b>${esc(CATEGORIES[c.c] || c.c)}</b></div>
          ${locals.length ? `<div class="fact"><small>Local names</small><b>${esc(locals.join(' · '))}</b></div>` : ''}
        </div>
        ${monthStrip(c)}
        <div class="guide-body">
          <div>
            <h2>About ${esc(c.n.toLowerCase())}</h2>
            <p>${esc(c.f || '')}</p>
            <h2>How to plant ${esc(c.n.toLowerCase())} well</h2>
            <p>${esc(c.t || '')}</p>
            <p>${esc(c.s || '')}</p>
            <h2>Diseases and pests of ${esc(c.n.toLowerCase())}</h2>
            <div class="our-list card"><ul>${c.d.map(d => `<li><b>${esc(d[0])}</b><span>${esc(d[1])}</span></li>`).join('')}</ul></div>
            <p><a class="btn btn-ghost" href="/doctor.html?crop=${c.id}">🩺 Something wrong with your ${esc(c.n.toLowerCase())}? Ask the Farm Doctor</a></p>
            <h2>Best states for ${esc(c.n.toLowerCase())}</h2>
            <p>${c.st.length ? c.st.map(stateLink).join(' · ') : 'Grown in small amounts in many states.'}</p>
            <h2>Questions farmers ask</h2>
            ${faqHTML(faq)}
          </div>
          <aside class="guide-aside">
            <div class="card">
              <h3>🌧️ Is it time to plant ${esc(c.n.toLowerCase())}?</h3>
              <p class="note">We check live rain and soil moisture for your state.</p>
              <a class="btn-gold" href="/planting.html?crop=${c.id}">Check my state</a>
            </div>
            ${related.length ? `<div class="card" style="margin-top:16px"><h3>More ${esc((CATEGORIES[c.c] || '').toLowerCase())}</h3><ul class="link-grid" style="grid-template-columns:1fr">${related.map(x => `<li><a href="/crops/${x.id}/">${esc(x.e || '')} ${esc(x.n)}</a></li>`).join('')}</ul></div>` : ''}
          </aside>
        </div>`;
  const title = `When to plant ${c.n} in Nigeria: planting & harvest months | Harvest Calendar Naija`;
  write(`crops/${c.id}/index.html`, page({
    rel: `crops/${c.id}/index.html`,
    title: title.length > 75 ? `When to plant ${c.n} in Nigeria | Harvest Calendar Naija` : title,
    description: `${c.n}${locals.length ? ' (' + locals.join(', ') + ')' : ''}: plant in ${plant}, harvest in ${harvest}. Best states, how to plant, diseases and prevention.`.slice(0, 158),
    keywords: [`when to plant ${c.n.toLowerCase()} in Nigeria`, `${c.n.toLowerCase()} planting season`, `${c.n.toLowerCase()} farming Nigeria`, ...locals].join(', '),
    crumbs: [['Home', '/'], ['Crops', '/crops/'], [c.n, `/crops/${c.id}/`]],
    h1: `${esc(c.e || '')} When to plant ${esc(c.n.toLowerCase())} in Nigeria`,
    sub: locals.length ? `Also called ${esc(list(cropLocal(c)))}.` : '',
    answer, body,
    schema: [
      { '@type': 'Article', headline: `When to plant ${c.n.toLowerCase()} in Nigeria`, description: plainAnswer, inLanguage: 'en-NG', datePublished: '2026-10-29', dateModified: TODAY,
        author: { '@id': URL_ + '/#org' }, publisher: { '@id': URL_ + '/#org' }, mainEntityOfPage: URL_ + `/crops/${c.id}/`, image: URL_ + '/images/og-image.png',
        about: { '@type': 'Thing', name: c.n, alternateName: locals } },
      faqLD(faq)
    ]
  }));
  pages.push({ loc: `/crops/${c.id}/`, pri: '0.7' });
});

/* ---------- /states/<state>/ ---------- */
const regionCrops = s => CROPS.filter(c => c.z.includes(s.z));
STATES.forEach(s => {
  const zone = ZONES[s.z].name;
  const best = CROPS.filter(c => c.st.includes(s.n));
  const fit = regionCrops(s);
  const byMonth = MONTHS.map((m, i) => ({
    m, plant: fit.filter(c => c.p.includes(i + 1)), harvest: fit.filter(c => c.h.includes(i + 1))
  }));
  const dry = fit.filter(c => c.p.some(m => [11, 12, 1, 2].includes(m))).slice(0, 8);
  const name = s.n === 'FCT' ? 'the FCT (Abuja)' : `${s.n} State`;
  const answer = `${esc(name)} is in Nigeria's <b>${esc(zone)}</b> (${esc(s.eco)}). The rainy season runs <b>${esc(s.rain)}</b>. ${best.length ? `Its best-known crops are <b>${esc(list(best.slice(0, 6).map(c => c.n.toLowerCase())))}</b>.` : ''} Plant rain-fed crops only after the rains have truly started.`;
  const plain = answer.replace(/<[^>]+>/g, '');
  const faq = [
    [`What crops grow best in ${name}?`, best.length ? `${list(best.map(c => c.n))} are among the best-known crops of ${name}.` : `${name} grows ${list(fit.slice(0, 8).map(c => c.n.toLowerCase()))} and more.`],
    [`When does the rainy season start in ${name}?`, `The rainy season in ${name} usually runs ${s.rain}. The rains have truly started when about 20 mm of rain falls within 3 days. Use our live check before you plant.`],
    [`What can I plant in ${name} in the dry season?`, dry.length ? `With irrigation or on fadama (wet valley) land: ${list(dry.map(c => c.n.toLowerCase()))}.` : `Most crops in ${name} wait for the rains. Small vegetable beds can be watered by hand.`],
    [`What should I plant in ${name} at the start of the rains?`, `${list(byMonth[(s.z === 'NW' || s.z === 'NE') ? 5 : 3].plant.slice(0, 8).map(c => c.n.toLowerCase()))} are commonly planted when the rains begin.`]
  ];
  const body = `
        <div class="facts">
          <div class="fact"><small>Region</small><b>${esc(zone)}</b></div>
          <div class="fact"><small>Rainy season</small><b>${esc(s.rain)}</b></div>
          <div class="fact"><small>Vegetation</small><b>${esc(s.eco)}</b></div>
          <div class="fact"><small>Capital (weather point)</small><b>${esc(s.cap)}</b></div>
        </div>
        <p><a class="btn-gold" href="/planting.html?state=${s.id}">🌧️ Live check: have the rains started in ${esc(s.n)}?</a></p>
        <div class="guide-body">
          <div>
            ${best.length ? `<h2>Best-known crops of ${esc(name)}</h2><ul class="link-grid">${best.map(c => `<li><a href="/crops/${c.id}/">${esc(c.e || '')} ${esc(c.n)}<small>plant ${esc(monthRange(c.p))}</small></a></li>`).join('')}</ul>` : ''}
            <h2>What to plant and harvest in ${esc(name)}, month by month</h2>
            <div class="table-wrap"><table class="crop-table"><thead><tr><th>Month</th><th>Plant</th><th>Harvest</th></tr></thead><tbody>
            ${byMonth.map(r => `<tr><th scope="row" style="background:transparent;color:inherit">${r.m}</th><td>${esc(r.plant.slice(0, 10).map(c => c.n).join(', ') || '-')}</td><td>${esc(r.harvest.slice(0, 10).map(c => c.n).join(', ') || '-')}</td></tr>`).join('')}
            </tbody></table></div>
            <h2>Questions farmers in ${esc(s.n)} ask</h2>
            ${faqHTML(faq)}
          </div>
          <aside class="guide-aside">
            <div class="card"><h3>Other ${esc(zone)} states</h3><ul class="link-grid" style="grid-template-columns:1fr">${STATES.filter(x => x.z === s.z && x.id !== s.id).map(x => `<li><a href="/states/${x.id}/">${esc(x.n)}</a></li>`).join('')}</ul></div>
          </aside>
        </div>`;
  write(`states/${s.id}/index.html`, page({
    rel: `states/${s.id}/index.html`,
    title: `What to plant in ${s.n === 'FCT' ? 'Abuja (FCT)' : s.n + ' State'}: crop calendar | Harvest Calendar Naija`,
    description: `Crop calendar for ${name}: rainy season ${s.rain}, best crops, what to plant and harvest each month, plus a live rain check.`.slice(0, 158),
    keywords: `what to plant in ${s.n}, ${s.n} farming, crop calendar ${s.n}, planting season ${s.n}, rainy season ${s.n}`,
    crumbs: [['Home', '/'], ['States', '/states/'], [s.n, `/states/${s.id}/`]],
    h1: `What to plant in ${esc(name)}`, answer, body,
    schema: [
      { '@type': 'Article', headline: `What to plant in ${name}`, description: plain, inLanguage: 'en-NG', datePublished: '2026-10-29', dateModified: TODAY,
        author: { '@id': URL_ + '/#org' }, publisher: { '@id': URL_ + '/#org' }, mainEntityOfPage: URL_ + `/states/${s.id}/`,
        spatialCoverage: { '@type': 'AdministrativeArea', name, containedInPlace: { '@type': 'Country', name: 'Nigeria' } } },
      faqLD(faq)
    ]
  }));
  pages.push({ loc: `/states/${s.id}/`, pri: '0.7' });
});

/* ---------- /crops/ and /states/ ---------- */
write('crops/index.html', page({
  rel: 'crops/index.html',
  title: `${CROPS.length} Nigerian crops: when to plant and harvest each one | Harvest Calendar Naija`,
  description: `Planting and harvest months for ${CROPS.length} Nigerian crops: grains, legumes, roots, vegetables, fruits and tree crops, with local names and diseases.`,
  crumbs: [['Home', '/'], ['Crops', '/crops/']],
  h1: 'Crop guides: when to plant every Nigerian crop',
  answer: `Most Nigerian crops are planted when the rains start: around <b>March to April in the South</b> and <b>May to June in the North</b>. Dry-season crops like wheat, onion and irrigated tomato are planted from November. Pick a crop below for its exact months.`,
  body: Object.entries(CATEGORIES).filter(([k]) => k !== 'my').map(([k, label]) => {
    const cs = CROPS.filter(c => c.c === k); if (!cs.length) return '';
    return `<h2>${esc(label)}</h2><ul class="link-grid">${cs.map(c => `<li><a href="/crops/${c.id}/">${esc(c.e || '')} ${esc(c.n)}<small>plant ${esc(monthRange(c.p))}</small></a></li>`).join('')}</ul>`;
  }).join('\n'),
  schema: [{ '@type': 'CollectionPage', name: 'Crop guides', dateModified: TODAY, publisher: { '@id': URL_ + '/#org' },
    hasPart: CROPS.map(c => ({ '@type': 'Article', headline: `When to plant ${c.n.toLowerCase()} in Nigeria`, url: URL_ + `/crops/${c.id}/` })) }]
}));
write('states/index.html', page({
  rel: 'states/index.html',
  title: 'What to plant in every Nigerian state: 36 states + FCT | Harvest Calendar Naija',
  description: 'Crop calendars for all 36 Nigerian states and the FCT: rainy season, best crops and what to plant each month, grouped by region.',
  crumbs: [['Home', '/'], ['States', '/states/']],
  h1: 'What to plant in your state',
  answer: 'The rains reach the <b>South first (March to April)</b> and the <b>far North last (June)</b>, so the right planting month depends on your state. Pick your state for its own calendar and a live rain check.',
  body: Object.entries(ZONES).map(([z, info]) => `<h2>${esc(info.name)}</h2><ul class="link-grid">${STATES.filter(s => s.z === z).map(s => `<li><a href="/states/${s.id}/">${esc(s.n)}<small>rains ${esc(s.rain)}</small></a></li>`).join('')}</ul>`).join('\n'),
  schema: [{ '@type': 'CollectionPage', name: 'State crop calendars', dateModified: TODAY, publisher: { '@id': URL_ + '/#org' } }]
}));

/* ---------- fix the address on the hand-made pages ---------- */
const MAIN = ['index.html', 'planting.html', 'doctor.html', 'crops.html', 'calendar.html', 'seasons.html', 'map.html', 'entries.html', 'tips.html'];
MAIN.forEach(f => {
  const file = path.join(ROOT, f);
  let h = fs.readFileSync(file, 'utf8');
  const url = URL_ + '/' + (f === 'index.html' ? '' : f);
  h = h.replace(/<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${url}">`)
       .replace(/<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${url}">`)
       .replace(/https:\/\/harvestcalendarnaija\.example/g, URL_)
       .replace(/family=Fraunces:opsz,wght@9\.\.144,500;9\.\.144,700/, 'family=Fraunces:opsz,wght@9..144,400..700');
  if (!h.includes('og:image')) h = h.replace('<meta property="og:locale"', `<meta property="og:image" content="${URL_}/images/og-image.png">\n  <meta property="og:locale"`);
  h = h.replace('<meta name="twitter:card" content="summary">', '<meta name="twitter:card" content="summary_large_image">');
  fs.writeFileSync(file, h);
  pages.unshift({ loc: f === 'index.html' ? '/' : '/' + f, pri: f === 'index.html' ? '1.0' : '0.8' });
});
pages.push({ loc: '/crops/', pri: '0.9' }, { loc: '/states/', pri: '0.9' });

